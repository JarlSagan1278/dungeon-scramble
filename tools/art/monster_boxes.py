#!/usr/bin/env python3
"""Writes MONSTER_ART_BOX into src/assets.js: where each monster's visible body sits inside its picture, as fractions
[x0, y0, x1, y1] of the picture (unflipped). The carried loot die (enemyCarryHTML, render.js) is placed against the
body, not the picture's empty margins. Run after adding or replacing monster art: python3 tools/art/monster_boxes.py"""
import re, os
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
p = os.path.join(ROOT, 'src', 'assets.js'); s = open(p).read()
block = s[s.index('const MONSTER_ART = {'):]; block = block[:block.index('\n};')]
rows = []
for name, path in re.findall(r"^\s*('(?:[^'\\]|\\.)*'|\"[^\"]*\")\s*:\s*\"art:([^\"]+)\"", block, re.M):
    im = Image.open(os.path.join(ROOT, 'src', 'art', path)).convert('RGBA')
    a = im.split()[3].point(lambda v: 255 if v > 40 else 0)
    bb = a.getbbox()
    if not bb: continue
    W, H = im.size
    rows.append(f"  {name}: [{bb[0]/W:.3f},{bb[1]/H:.3f},{bb[2]/W:.3f},{bb[3]/H:.3f}],")
out = "// MONSTER_ART_BOX: generated by tools/art/monster_boxes.py (each monster's visible body inside its picture).\nconst MONSTER_ART_BOX = {\n" + "\n".join(rows) + "\n};\n"
s = re.sub(r"// MONSTER_ART_BOX: generated.*?\n};\n", lambda m: out, s, flags=re.S) if 'const MONSTER_ART_BOX' in s else s.replace('const LOOT_ART = {', out + 'const LOOT_ART = {', 1)
open(p, 'w').write(s); print(len(rows), 'monster boxes')

# Copies sketch notes from docs/music/sketches.json into src/music.js (between the NOTES markers).
# Run after changing tools/music/make_sketches.py:  python3 tools/music/make_sketches.py && python3 tools/music/sync_game_music.py
import json, os, re
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
sk = {s['id']: s for s in json.load(open(os.path.join(ROOT, 'docs/music/sketches.json')))}
def parts(sid):
    return {p['role']: [n for n in p['notes'] if n[0] < sk[sid]['beats']] for p in sk[sid]['parts']}
down, act = parts('05_downtime_sketch_Dm_140'), parts('06_action_sketch_Dm_140')
J = lambda x: json.dumps(x, separators=(',', ':'))
block = ("// NOTES (generated by tools/music/sync_game_music.py -- don't edit by hand)\n"
         "const MUSIC_NOTES = {\n"
         "  down: { bass:" + J(down['bass']) + ",\n         lead:" + J(down['lead']) + " },\n"
         "  act:  { bass:" + J(act['bass']) + ",\n         lead:" + J(act['lead']) + ",\n         drums:" + J(act['drums']) + " },\n"
         "};\n// /NOTES\n")
p = os.path.join(ROOT, 'src/music.js'); s = open(p).read()
s = re.sub(r"// NOTES \(generated.*?// /NOTES\n", lambda m: block, s, count=1, flags=re.S)
open(p, 'w').write(s); print('synced')

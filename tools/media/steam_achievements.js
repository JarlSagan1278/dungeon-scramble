// Steam achievements (Nov 25): the list Steamworks needs plus a 256x256 icon pair per achievement, drawn from the game's
// own medal coins (earned: bronze/silver/gold coin with its symbol; locked: the dark coin).
// usage: node build.js --steam && node tools/media/steam_achievements.js
//   -> docs/release/steam_achievements.md (committed: API names, names, descriptions, hidden flags)
//   -> docs/release/media/steam/achievements/<API_NAME>.png and <API_NAME>_locked.png (git-ignored; upload in Steamworks)
const path = require('path'), fs = require('fs');
let chromium; try { ({ chromium } = require('playwright')); } catch (e) { ({ chromium } = require('/opt/node22/lib/node_modules/playwright')); }
const ROOT = path.resolve(__dirname, '../..'), OUT = path.join(ROOT, 'docs/release/media/steam/achievements');
fs.mkdirSync(OUT, { recursive: true });
const HIDDEN = new Set([]); // none secret yet; the Easter egg has no medal (keeps it a surprise)
(async () => {
  const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 300, height: 300 } });
  const html = fs.existsSync(path.join(ROOT, 'dist/steam/dungeon_scramble.html')) ? 'dist/steam/dungeon_scramble.html' : 'dist/release/dungeon_scramble.html';
  await p.goto('file://' + path.join(ROOT, html)); await p.waitForTimeout(1200);
  const list = await p.evaluate(() => achievementsShown().map(a => ({ id: a.id, api: a.id.toUpperCase(), name: a.name, desc: a.desc, tier: a.tier || '' })));
  await p.evaluate(() => { document.body.innerHTML = '<div id="ic" style="position:fixed;left:0;top:0;width:256px;height:256px;display:flex;align-items:center;justify-content:center;background:#2b1d14"></div>';
    const s = document.createElement('style'); s.textContent = '#ic .achv-medal{zoom:4.2; display:flex; flex-direction:column; align-items:center;} #ic .achv-mname{display:none}'; document.head.appendChild(s); });
  for (const a of list) {
    for (const on of [true, false]) {
      await p.evaluate(({ a, on }) => { document.getElementById('ic').innerHTML = `<div class="achv-medal ${on ? 'on' : ''} ${a.tier ? 'tier-' + a.tier : ''}"><span class="achv-coin">${iconSpanSolid(ACH_ICON[a.id] || 'combo')}</span></div>`; }, { a, on });
      await p.waitForTimeout(40);
      await p.screenshot({ path: path.join(OUT, a.api + (on ? '' : '_locked') + '.png'), clip: { x: 0, y: 0, width: 256, height: 256 } });
    }
  }
  await b.close();
  const md = ['# Steam achievements', '', `Generated by tools/media/steam_achievements.js from build ${require(path.join(ROOT, 'package.json')).version} (${list.length} achievements; the store app's purchase medal is left out on Steam).`,
    'Enter each in Steamworks > App Admin > Stats & Achievements > Achievements: API name, display name, description, hidden, and the two icons from',
    'docs/release/media/steam/achievements/ (API_NAME.png earned, API_NAME_locked.png not yet). The game reports the API name (the id in upper case) through steam/main.js.', '',
    '| API name | Name | Description | Tier | Hidden |', '|---|---|---|---|---|',
    ...list.map(a => `| ${a.api} | ${a.name} | ${a.desc.replace(/\|/g, '/')} | ${a.tier || '-'} | ${HIDDEN.has(a.id) ? 'yes' : 'no'} |`)];
  fs.writeFileSync(path.join(ROOT, 'docs/release/steam_achievements.md'), md.join('\n') + '\n');
  console.log(list.length, 'achievements ->', OUT);
})();
